# Prepare VidHub for Windows on the first run, then refresh dependencies on later runs.
# Run from anywhere:  powershell -ExecutionPolicy Bypass -File scripts\setup.ps1

$ErrorActionPreference = 'Stop'
Set-Location (Split-Path -Parent $PSScriptRoot)

if (-not (Get-Command flutter -ErrorAction SilentlyContinue)) {
  throw 'Flutter is not on PATH. Install it from https://docs.flutter.dev/get-started/install/windows'
}

if (-not (Test-Path 'windows\CMakeLists.txt')) {
  # Suppress Flutter's sample mobile and widget test files in this desktop app.
  flutter create --platforms=windows --project-name vidhub --org dev.vidhub .
  if ($LASTEXITCODE -ne 0) { throw 'Flutter could not generate the Windows runner.' }
}

# Remove the default counter smoke test generated by flutter create.
if (Test-Path 'test\widget_test.dart') {
  $templateTest = Get-Content 'test\widget_test.dart' -Raw
  if ($templateTest -match 'Counter increments smoke test' -and $templateTest -match 'MyApp\(') {
    Remove-Item 'test\widget_test.dart' -Force
  }
}

# Set the Windows window title and version metadata to VidHub. Keep Flutter's
# internal CMake target name unchanged for compatibility with its generated files.
(Get-Content 'windows\runner\main.cpp' -Raw).Replace('window.Create(L"taskpulse"', 'window.Create(L"VidHub"') | Set-Content 'windows\runner\main.cpp' -NoNewline
(Get-Content 'windows\runner\Runner.rc' -Raw).Replace('dev.taskpulse', 'VidHub').Replace('taskpulse.exe', 'vidhub.exe').Replace('"taskpulse"', '"VidHub"') | Set-Content 'windows\runner\Runner.rc' -NoNewline

# Use the VidHub icon for the .exe too.
Copy-Item 'assets\icons\tray.ico' 'windows\runner\resources\app_icon.ico' -Force

flutter pub get
if ($LASTEXITCODE -ne 0) { throw 'flutter pub get failed.' }
flutter analyze
if ($LASTEXITCODE -ne 0) { throw 'flutter analyze reported issues.' }
flutter test
if ($LASTEXITCODE -ne 0) { throw 'flutter test failed.' }

# Flutter's CMake template pins the runner output to the project name. Keep its
# internal target and bundle paths stable, then rename the built app file.
foreach ($configuration in @('Debug', 'Profile', 'Release')) {
  $runnerDir = Join-Path 'build\windows\x64\runner' $configuration
  $oldExe = Join-Path $runnerDir 'taskpulse.exe'
  if (Test-Path $oldExe) {
    Move-Item -LiteralPath $oldExe -Destination (Join-Path $runnerDir 'vidhub.exe') -Force
  }
}

Write-Host ''
Write-Host 'Ready. Start VidHub with:  flutter run -d windows' -ForegroundColor Green
